#pragma once

#include <memory>
#include "DDataMgrBase.h"

/** ***********************************************************
 * @brief       笔记数据缓冲区接口
 * @Detail:     定义数据收集和读取的标准接口，用于解耦读写线程和具体实现
 ************************************************************/
class INoteDataBuffer
{
public:
    virtual ~INoteDataBuffer() = default;

    /** ***********************************************************
     * @brief       追加UI层数据到缓冲区（写入端）
     * @param[in]   stModelItem UI层数据结构
     ************************************************************/
    virtual void AppendData(const NOTE_MODEL_ITEM &stModelItem) = 0;

    /** ***********************************************************
     * @brief       从缓冲区读取原始字节数据（读取端）
     * @param[in]   s32GetSize 请求读取的大小
     * @param[out]  pcBuffer 输出缓冲区
     * @return      实际读取的字节数，-1 表示错误
     ************************************************************/
    virtual INT32 ReadBuffer(INT32 s32GetSize, char *pcBuffer) = 0;

    /** ***********************************************************
     * @brief       检查缓冲区是否有未读数据
     * @return      true 有数据 / false 无数据
     ************************************************************/
    virtual bool HasData() const = 0;

    /** ***********************************************************
     * @brief       清空缓冲区
     ************************************************************/
    virtual void Clear() = 0;

    /** ***********************************************************
     * @brief       获取缓冲区总大小
     * @return      缓冲区容量（字节）
     ************************************************************/
    virtual INT32 GetBufferSize() const = 0;
};